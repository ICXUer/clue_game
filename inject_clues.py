def build_default_data():
    clues = {}
    round1_pool = []
    round2_pool = []
    for num, belong, act, desc in CLUES:
        cid = f"c{num:02d}"
        btype = "location" if belong in LOCATION_NAMES else "role"
        clues[cid] = {
            "belong_type": btype,
            "belong_name": belong,
            "desc": desc,
            "img": "",
            "can_public": True
        }
        if act == 1:
            round1_pool.append(cid)
        else:
            round2_pool.append(cid)
    return {
        "roles": ROLES,
        "rounds": {
            "1": {"open": False, "per_person_draw": 2, "pool": round1_pool},
            "2": {"open": False, "per_person_draw": 2, "pool": round2_pool}
        },
        "clues": clues,
        "draw_log": {},
        "dm_public_pool": []
    }

def main():
    with open(r"D:\桌面\index.html", "r", encoding="utf-8") as f:
        html = f.read()

    default_data = build_default_data()
    # 用JSON序列化，ensure_ascii=False保留中文
    data_json = json.dumps(default_data, ensure_ascii=False, indent=2)

    # 替换loadData函数的默认返回值
    old_block = """  return {
    roles:[],
    rounds:{},
    clues:{},
    draw_log:{},
    dm_public_pool:[]
  }"""

    new_block = "  return " + data_json

    if old_block not in html:
        print("ERROR: 未找到默认数据块")
        return

    html = html.replace(old_block, new_block)

    with open(r"D:\桌面\index.html", "w", encoding="utf-8") as f:
        f.write(html)

    dd = build_default_data()
    print(f"完成！共注入 {len(CLUES)} 条线索")
    print(f"  第一幕: {len(dd['rounds']['1']['pool'])} 条")
    print(f"  第二幕: {len(dd['rounds']['2']['pool'])} 条")
    print(f"  角色: {len(ROLES)} 个")

if __name__ == "__main__":
    main()
